"""A Sigshell session: one folder holding inputs, R step scripts, outputs, a call log and a replay script.

Layout of ~/Sigshell/sessions/<YYYYMMDD-HHMMSS>/:
  inputs/      copies of the files the user analysed, prefixed with their SHA-256
  steps/       NNN-<tool>.R, each runnable on its own with `Rscript steps/NNN-<tool>.R`
  outputs/     results (CSV, RDS, PNG, JSON) named by step
  calls.jsonl  one line per tool call: time, tool, arguments, duration, status
  steps.json   whether each attempted R step is pending, succeeded or failed
  session.R    the preamble followed by successful steps in order: `cd <session> && Rscript session.R`
"""

from __future__ import annotations

import hashlib
import json
import shutil
import time
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any

from . import config, rbridge


@dataclass
class Result:
    id: str
    kind: str  # "scores" or "significance"
    step: str
    scores: list[str]
    samples: list[str]
    files: dict[str, str] = field(default_factory=dict)


class Session:
    def __init__(self, root: Path | None = None):
        self._root = root
        self._dir: Path | None = None
        self._n = 0
        self.results: dict[str, Result] = {}
        self._staged: dict[str, str] = {}
        self._steps: dict[str, dict[str, str]] = {}

    @property
    def started(self) -> Path | None:
        """The session folder, or None if nothing has run yet (reading `dir` would create it)."""
        return self._dir

    @property
    def dir(self) -> Path:
        if self._dir is None:
            base = self._root or config.SESSIONS_DIR
            stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
            d = base / stamp
            k = 1
            while d.exists():
                k += 1
                d = base / f"{stamp}-{k}"
            for sub in ("inputs", "steps", "outputs"):
                (d / sub).mkdir(parents=True, exist_ok=True)
            self._dir = d
            self._write_script()
        return self._dir

    def next_step(self) -> str:
        self._n += 1
        return f"{self._n:03d}"

    def stage_input(self, path: Path) -> str:
        """Copy an input file into the session so the replay script never depends on the original."""
        path = path.expanduser().resolve()
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        key = f"{digest}:{path.name}"
        if key not in self._staged:
            rel = f"inputs/{digest[:8]}-{path.name}"
            shutil.copy2(path, self.dir / rel)
            self._staged[key] = rel
        return self._staged[key]

    def record_environment(self, commit: str, versions: dict[str, Any]) -> None:
        """Keep the exact software environment with the exported analysis."""
        path = self.dir / "provenance.json"
        path.write_text(json.dumps({"sigscores_commit": commit, "versions": versions}, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        self._write_script()

    def write_step(self, step: str, tool: str, arguments: dict[str, Any], body: str) -> Path:
        """Write steps/<step>-<tool>.R: the preamble followed by this step's code."""
        header = f"## ---- Step {step}: {tool} ({datetime.now():%Y-%m-%d %H:%M:%S}) ----\n## Arguments: {json.dumps(arguments, sort_keys=True)}\n"
        path = self.dir / "steps" / f"{step}-{tool}.R"
        path.write_text(rbridge.preamble() + "\n" + header + body.strip() + "\n", encoding="utf-8")
        self._steps[step] = {"file": path.name, "status": "pending"}
        self._save_step_status()
        return path

    def _save_step_status(self) -> None:
        path = self.dir / "steps.json"
        temporary = path.with_suffix(".json.tmp")
        temporary.write_text(json.dumps(self._steps, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        temporary.replace(path)

    def finish_step(self, step: str, *, succeeded: bool) -> None:
        """Keep failed attempts for inspection, but replay only completed steps."""
        self._steps[step]["status"] = "succeeded" if succeeded else "failed"
        self._save_step_status()
        self._write_script()

    def step_files(self) -> list[Path]:
        return [self.dir / "steps" / entry["file"] for _, entry in sorted(self._steps.items())
                if entry["status"] == "succeeded"]

    def _write_script(self) -> None:
        parts = [
            "## Sigshell session replay script. Run it from this folder:  Rscript session.R",
            f"## Generated by Sigshell for sigscores commit {config.EXPECTED_COMMIT[:7]}.",
            "## Exact R and package versions are recorded in provenance.json.",
            "## Only successful steps are replayed; all attempts are retained in steps/ and steps.json.",
            "",
            rbridge.preamble(),
        ]
        pre = rbridge.preamble()
        for f in self.step_files():
            text = f.read_text(encoding="utf-8")
            parts.append(text[len(pre):] if text.startswith(pre) else text)
        (self._dir / "session.R").write_text("\n".join(parts), encoding="utf-8")  # type: ignore[operator]

    def refresh_script(self) -> Path:
        self._write_script()
        return self.dir / "session.R"

    def log(self, tool: str, arguments: dict[str, Any], started: float, status: str, detail: str = "", step: str | None = None) -> None:
        entry = {
            "time": datetime.fromtimestamp(started).isoformat(timespec="seconds"),
            "tool": tool,
            "arguments": arguments,
            "duration_s": round(time.time() - started, 3),
            "status": status,
            "step": step,
            "detail": detail[:2000],
        }
        with (self.dir / "calls.jsonl").open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(entry) + "\n")
